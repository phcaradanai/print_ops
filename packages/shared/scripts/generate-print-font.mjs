// Regenerates src/print-font.generated.ts from @fontsource/noto-sans-thai.
// Run: node packages/shared/scripts/generate-print-font.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@fontsource/noto-sans-thai/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

// Same unicode ranges fontsource uses, so each subset only loads when needed.
const SUBSETS = {
  thai: 'U+02D7,U+0303,U+0331,U+0E01-0E5B,U+200C-200D,U+25CC',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};

/** Codepoints listed by a CSS unicode-range string. */
function codepoints(range) {
  return range.split(',').flatMap((part) => {
    const [from, to = from] = part.replace('U+', '').split('-').map((hex) => parseInt(hex, 16));
    return Array.from({ length: to - from + 1 }, (_, i) => from + i);
  });
}

const faces = [];
// Advance width per codepoint in em, per weight: lets the server size
// shrink-to-fit text exactly as the canvas renders it, without a browser.
const advances = { 400: {}, 700: {} };
for (const weight of [400, 700]) {
  for (const [subset, range] of Object.entries(SUBSETS)) {
    const file = readFileSync(join(pkgDir, 'files', `noto-sans-thai-${subset}-${weight}-normal.woff`));
    const font = opentype.parse(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength));
    for (const cp of codepoints(range)) {
      const glyph = font.charToGlyph(String.fromCodePoint(cp));
      if (glyph.index !== 0) advances[weight][cp] = Math.round((glyph.advanceWidth / font.unitsPerEm) * 1000) / 1000;
    }
    const data = readFileSync(join(pkgDir, 'files', `noto-sans-thai-${subset}-${weight}-normal.woff2`)).toString('base64');
    faces.push(`@font-face{font-family:"PrintOps Label Sans";font-style:normal;font-weight:${weight};font-display:block;`
      + `src:url(data:font/woff2;base64,${data}) format("woff2");unicode-range:${range};}`);
  }
}

const out = `// GENERATED by scripts/generate-print-font.mjs from @fontsource/noto-sans-thai@${version}
// (Noto Sans Thai, SIL Open Font License 1.1). Do not edit by hand.
export const PRINT_FONT_FACE_CSS = ${JSON.stringify(faces.join(''))};
/** Advance width in em by codepoint, for weights 400 and 700. */
export const PRINT_FONT_ADVANCES_EM: Record<400 | 700, Record<number, number>> = ${JSON.stringify(advances)};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'print-font.generated.ts'), out);
console.log(`wrote ${out.length} bytes`);
